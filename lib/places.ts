/** Closest reference town (great-circle), as Sentinel's admin does it. */
export function nearestPlace(lat: number, lng: number) {
  const r = Math.PI / 180;
  let best = { name: "", province: "", km: Infinity };
  for (const [name, province, plat, plng] of PLACES) {
    const dLat = (plat - lat) * r;
    const dLng = (plng - lng) * r;
    const h = Math.sin(dLat / 2) ** 2 + Math.cos(lat * r) * Math.cos(plat * r) * Math.sin(dLng / 2) ** 2;
    const km = 12742 * Math.asin(Math.sqrt(h));
    if (km < best.km) best = { name, province, km };
  }
  return { ...best, km: Math.round(best.km) };
}

/** "a 12 km de El Bolsón (Río Negro)", or "en El Bolsón (Río Negro)" when within 3 km. */
export function placeLabel(lat: number, lng: number) {
  const p = nearestPlace(lat, lng);
  return p.km <= 3 ? `en ${p.name} (${p.province})` : `a ${p.km} km de ${p.name} (${p.province})`;
}
